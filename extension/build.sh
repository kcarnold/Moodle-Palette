#!/bin/bash
# Vendor fuzzysort into lib/fuzzysort.js as a classic script defining a global `fuzzysort`.
# (fuzzysort ships ESM only; content scripts in the MAIN world are classic scripts.)
# Run this whenever you need to update the fuzzysort dependency.

set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
FUZZYSORT_VERSION="${FUZZYSORT_VERSION:-4.0.2}"

TMPDIR=$(mktemp -d)
trap 'rm -rf "$TMPDIR"' EXIT

echo "Installing fuzzysort@$FUZZYSORT_VERSION into temp directory..."
(cd "$TMPDIR" && npm init -y --silent >/dev/null && npm install "fuzzysort@$FUZZYSORT_VERSION" --silent) 2>&1 | tail -1

echo "Bundling with esbuild (IIFE, global fuzzysort)..."
mkdir -p "$SCRIPT_DIR/lib"
(cd "$TMPDIR" && npx --yes esbuild fuzzysort \
  --bundle --format=iife --global-name=fuzzysort \
  --banner:js="// fuzzysort $FUZZYSORT_VERSION (MIT, https://github.com/farzher/fuzzysort). Generated by build.sh; do not edit." \
  --outfile="$SCRIPT_DIR/lib/fuzzysort.js")

echo "Done. lib/fuzzysort.js is ready."
ls -lh "$SCRIPT_DIR/lib/fuzzysort.js"
